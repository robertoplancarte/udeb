#!/bin/sh
# Runs before every `neptuno up` (hooks.before_up in neptuno.yml).
set -eu

# Hook0 keys, generated once per machine so they never reach git:
# environments/hook0/keys.local.env for the Hook0 services in compose.yml,
# and environments/_shared/hook0.local.env so every repo gets the same
# master key as HOOK0_API_KEY. Delete both files to get new keys.
hook0_keys=environments/hook0/keys.local.env
hook0_shared=environments/_shared/hook0.local.env
if [ ! -f "$hook0_keys" ] || [ ! -f "$hook0_shared" ]; then
  master_key=$(uuidgen 2>/dev/null || cat /proc/sys/kernel/random/uuid)
  master_key=$(printf %s "$master_key" | tr 'A-Z' 'a-z')
  mkdir -p environments/hook0
  cat > "$hook0_keys" <<KEYS
# Generated by scripts/before_up.sh. MASTER_API_KEY must match HOOK0_API_KEY
# in _shared/hook0.local.env.
BISCUIT_PRIVATE_KEY=$(openssl rand -hex 32)
MASTER_API_KEY=$master_key
KEYS
  cat > "$hook0_shared" <<KEYS
# Generated by scripts/before_up.sh: Hook0's MASTER_API_KEY, sent as
# "Authorization: Bearer <key>".
HOOK0_API_KEY=$master_key
KEYS
  echo "Generated Hook0 keys in $hook0_keys and $hook0_shared"
fi
